import axios from 'axios';

const API_URL = import.meta.env.VITE_BACKEND_URL || (import.meta.env.DEV ? 'http://localhost:3001' : window.location.origin);
export const api = axios.create({ baseURL: API_URL });
api.interceptors.request.use((config) => {
  const token = localStorage.getItem('messenger_token');
  if (token) config.headers.Authorization = `Bearer ${token}`;
  return config;
});
const configuredWebsocketUrl = import.meta.env.VITE_WEBSOCKET_URL || API_URL.replace(/^http/, 'ws');
export const websocketUrl = configuredWebsocketUrl.replace(/\/$/, '').endsWith('/ws') ? configuredWebsocketUrl.replace(/\/$/, '') : `${configuredWebsocketUrl.replace(/\/$/, '')}/ws`;
export const signIn = (data) => api.post('/auth/sign-in', data);
export const signInWithMicrosoft = (idToken) => api.post('/auth/microsoft', { id_token: idToken });
export const signUp = (data) => api.post('/auth/sign-up', data);
export const checkToken = () => api.get('/auth/check-token');
export const getAdminMetrics = () => api.get('/admin/metrics', { params: { _nocache: Date.now() }, headers: { 'Cache-Control': 'no-cache', Pragma: 'no-cache' } });
export const getAdmins = () => api.get('/admin/admins');
export const addAdmin = (email) => api.post('/admin/admins', { email });
export const removeAdmin = (email) => api.delete(`/admin/admins/${encodeURIComponent(email)}`);
export const getUsers = (search = '') => api.get('/users', { params: search ? { search } : undefined });
export const getFriends = () => api.get('/friends');
export const getContactPreferences = () => api.get('/contact-preferences');
export const saveContactPreferences = (preferences) => api.put('/contact-preferences', { preferences });
export const getFriendRequests = () => api.get('/friend-requests');
export const sendFriendRequest = (userId, message) => api.post('/friend-requests', { userId, message });
export const respondToFriendRequest = (requestId, status) => api.patch(`/friend-requests/${requestId}`, { status });
export const startConversation = (userId) => api.post('/conversations', { userId });
export const getChats = (params = {}) => api.get('/messages/chats', { params });
export const getUnreadChats = () => api.get('/messages/unread');
export const getChatMessages = (chatId, params = {}) => api.get(`/messages/chat/${chatId}`, { params });
export const sendMessage = (data) => api.post('/messages', data);
export const resetUnread = (chatId) => api.post('/unread-messages/reset', { chatId });
export const updateBio = (bio) => api.patch('/users/bio', { bio });
export const updateUsername = (username) => api.patch('/users/username', { username });
export const updateAvatar = (avatar) => api.patch('/users/avatar', { avatar });
export const getMusicTracks = (folderId) => api.get('/music/tracks', { params: folderId ? { folderId } : {} });
export const getMusicTrack = (id) => api.get(`/music/tracks/${encodeURIComponent(id)}`);
export const getMusicFolders = () => api.get('/music/folders');
export const createMusicFolder = (name) => api.post('/music/folders', { name });
export const addMusicTrack = (track) => api.post('/music/tracks', track);
export const removeMusicTrack = (trackId) => api.delete(`/music/tracks/${trackId}`);
export const getListeningActivities = () => api.get('/music/listening');
export const getListeningPreference = () => api.get('/music/listening-preference');
export const saveListeningPreference = (share) => api.put('/music/listening-preference', { share });
